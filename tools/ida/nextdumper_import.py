"""Import NextDumper reflection metadata into the current IDA database."""

import json
import os
import re


MAX_JSON_BYTES = 512 * 1024 * 1024
MAX_TYPES = 50000
MAX_ENUMS = 50000
MAX_FUNCTIONS = 1000000
MAX_PROPERTIES = 1000000
MAX_TYPE_SIZE = 16 * 1024 * 1024
MAX_HEADER_BYTES = 64 * 1024 * 1024
MAX_COMMENT_CHARS = 4096
MAX_IDENTIFIER_CHARS = 128


def _read_json(path, expected_version):
    if os.path.getsize(path) > MAX_JSON_BYTES:
        raise ValueError("JSON input exceeds the configured 512 MiB limit: " + path)
    with open(path, "r", encoding="utf-8") as source:
        value = json.load(source)
    if not isinstance(value, dict) or value.get("schema_version") != expected_version:
        raise ValueError("Unsupported JSON schema version: " + path)
    return value


REFLECTION_SCHEMA_VERSION = 11


def _shard_paths(artifact_dir, index):
    """Shard names come from the artifact and are untrusted: accept bare file names only."""
    shards = index.get("shards")
    if not isinstance(shards, list):
        raise ValueError("reflection.json has no shard list")
    paths = []
    for shard in shards:
        if not isinstance(shard, dict):
            raise ValueError("reflection.json shard entry is not an object")
        name = str(shard.get("file", ""))
        if not name or name in (".", "..") or os.path.basename(name) != name:
            raise ValueError("reflection.json shard has an unsafe file name: " + name)
        if os.sep in name or (os.altsep and os.altsep in name):
            raise ValueError("reflection.json shard has an unsafe file name: " + name)
        paths.append(os.path.join(artifact_dir, name))
    return paths


def _iter_shard_section(artifact_dir, index, section):
    """Yield records of one section across shards, holding a single shard in memory at a time."""
    for path in _shard_paths(artifact_dir, index):
        shard = _read_json(path, REFLECTION_SCHEMA_VERSION)
        items = shard.get(section, [])
        if not isinstance(items, list):
            raise ValueError("Shard section is not a list: " + section + " in " + path)
        for item in items:
            yield item
        del shard


def _as_int(value):
    if isinstance(value, bool):
        raise ValueError("Boolean is not an integer address")
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        return int(value, 0)
    raise ValueError("Expected an integer or hexadecimal string")


def _identifier(value, fallback):
    value = re.sub(r"[^A-Za-z0-9_]", "_", str(value)[:MAX_IDENTIFIER_CHARS])
    if not value:
        value = fallback
    if value[0].isdigit():
        value = "_" + value
    return value


def _unique_identifier(value, used, fallback):
    stem = _identifier(value, fallback)
    name = stem
    suffix = 1
    while name in used:
        name = stem + "_" + str(suffix)
        suffix += 1
    used.add(name)
    return name


def _comment_text(value):
    text = str(value)[:MAX_COMMENT_CHARS].replace("\r", " ").replace("\n", " ")
    return text.replace("*/", "* /")


def _safe_enum_value(value):
    value = _as_int(value)
    if value < -0x80000000 or value > 0x7FFFFFFF:
        return None
    return value


def _count_shards(index, section):
    shards = index.get("shards")
    if not isinstance(shards, list):
        raise ValueError("reflection.json has no shard list")
    total = 0
    for shard in shards:
        if not isinstance(shard, dict):
            raise ValueError("reflection.json shard entry is not an object")
        total += _as_int(shard.get(section, 0))
    return total


def _build_types_header(artifact_dir, index):
    type_count = _count_shards(index, "types")
    enum_count = _count_shards(index, "enums")
    function_count = _count_shards(index, "functions")
    if type_count > MAX_TYPES:
        raise ValueError("Type count is invalid or exceeds the configured limit")
    if enum_count > MAX_ENUMS:
        raise ValueError("Enum count is invalid or exceeds the configured limit")
    if function_count > MAX_FUNCTIONS:
        raise ValueError("Function count is invalid or exceeds the configured limit")

    output = []
    output_size = 0

    def emit(line):
        nonlocal output_size
        output_size += len(line.encode("utf-8"))
        if output_size > MAX_HEADER_BYTES:
            raise ValueError("Generated IDA type header exceeds the configured 64 MiB limit")
        output.append(line)

    emit("/* Generated by NextDumper. These are target-memory descriptions, not native ABI declarations. */\n")
    emit("/* No runtime object addresses are applied as static data addresses. */\n\n")

    used_enum_names = set()
    for enum in _iter_shard_section(artifact_dir, index, "enums"):
        if not isinstance(enum, dict):
            continue
        values = enum.get("values", [])
        if not isinstance(values, list) or not values:
            continue
        parsed_values = []
        valid = True
        local_names = set()
        enum_name = _unique_identifier("NextDumperEnum_" + str(enum.get("name", "Enum")), used_enum_names, "NextDumperEnum")
        for value in values:
            try:
                enum_value = _safe_enum_value(value.get("value"))
            except (TypeError, ValueError):
                enum_value = None
            if enum_value is None:
                valid = False
                break
            member_name = _unique_identifier(
                enum_name + "_" + str(value.get("name", "Value")), local_names, enum_name + "_Value"
            )
            parsed_values.append((member_name, enum_value))
        if not valid:
            emit("/* Enum omitted from IDA C types because one or more values do not fit a 32-bit C enum: ")
            emit(_comment_text(enum.get("full_name", enum.get("name", "unknown"))))
            emit(" */\n")
            continue
        emit("typedef enum " + enum_name + "\n{\n")
        for member_name, enum_value in parsed_values:
            emit("    " + member_name + " = " + str(enum_value) + ",\n")
        emit("} " + enum_name + ";\n\n")

    total_properties = 0
    used_type_names = set()
    # A base type may live in another shard: collect address-to-size first, then emit types.
    address_to_size = {}
    for item in _iter_shard_section(artifact_dir, index, "types"):
        if isinstance(item, dict):
            try:
                address_to_size[_as_int(item.get("address"))] = _as_int(item.get("size"))
            except (TypeError, ValueError):
                continue

    for item in _iter_shard_section(artifact_dir, index, "types"):
        if not isinstance(item, dict):
            continue
        try:
            type_size = _as_int(item.get("size"))
        except (TypeError, ValueError):
            continue
        if type_size <= 0 or type_size > MAX_TYPE_SIZE:
            emit("/* Type skipped: invalid or over-limit reflected size. */\n")
            continue

        generation = item.get("generation", {})
        if not isinstance(generation, dict):
            generation = {}
        generated_name = str(generation.get("cpp_name", item.get("name", "Type")))
        type_name = _unique_identifier("NextDumper_" + generated_name, used_type_names, "NextDumper_Type")
        full_name = _comment_text(item.get("full_name", item.get("name", "unknown")))
        emit("/* " + full_name + " | target size: " + str(type_size) + " bytes */\n")
        emit("typedef struct " + type_name + "\n{\n")

        cursor = 0
        super_address = 0
        try:
            super_address = _as_int(item.get("super", "0x0"))
        except (TypeError, ValueError):
            pass
        base_size = address_to_size.get(super_address, 0) if super_address else 0
        if 0 < base_size <= type_size:
            emit("    unsigned char _BaseStorage[" + str(base_size) + "]; /* reflected base extent */\n")
            cursor = base_size

        properties = item.get("properties", [])
        if not isinstance(properties, list):
            properties = []
        total_properties += len(properties)
        if total_properties > MAX_PROPERTIES:
            raise ValueError("Property count exceeds the configured 1,000,000 limit")

        candidates = []
        for property_item in properties:
            if not isinstance(property_item, dict):
                continue
            try:
                offset = _as_int(property_item.get("offset"))
                storage_size = _as_int(property_item.get("storage_size"))
            except (TypeError, ValueError):
                continue
            if offset < 0 or storage_size <= 0 or offset > type_size or storage_size > type_size - offset:
                continue
            candidates.append((offset, storage_size, property_item))
        candidates.sort(key=lambda field: (field[0], field[1], str(field[2].get("name", ""))))

        used_fields = set()
        for offset, storage_size, property_item in candidates:
            if offset < cursor:
                emit("    /* Overlapping field omitted: ")
                emit(_comment_text(property_item.get("name", "unknown")))
                emit(" at 0x" + format(offset, "X") + " */\n")
                continue
            if offset > cursor:
                emit("    unsigned char _pad_" + format(cursor, "X") + "[" + str(offset - cursor) + "];\n")
            field_name = _unique_identifier(property_item.get("name", "Field"), used_fields, "Field")
            kind = _comment_text(property_item.get("kind", "Unknown"))
            detail = "    unsigned char " + field_name + "[" + str(storage_size) + "]; /* " + kind
            if property_item.get("kind") == "Bool":
                layout = property_item.get("bool_layout", {})
                if isinstance(layout, dict):
                    detail += " mask=0x" + format(_as_int(layout.get("field_mask", 0)), "X")
            detail += " */\n"
            emit(detail)
            cursor = offset + storage_size

        if cursor < type_size:
            emit("    unsigned char _tail_" + format(cursor, "X") + "[" + str(type_size - cursor) + "];\n")
        emit("} " + type_name + ";\n\n")

    return "".join(output), type_count, enum_count, total_properties


def _default_name(name, ea):
    if not name:
        return True
    if name.lower() in ("nullsub", "unknown_libname"):
        return True
    return re.match(r"^(sub|loc|unk|nullsub)_[0-9a-f]+$", name, re.IGNORECASE) is not None


def _function_comment(function, entry_kind):
    lines = [
        "NextDumper " + entry_kind,
        "Reflected function: " + _comment_text(function.get("full_name", function.get("name", "unknown"))),
        "Entry kind: " + _comment_text(function.get("entry_kind", "unknown")),
        "Function status: " + _comment_text(function.get("status", "unknown")),
    ]
    parameters = function.get("parameters", [])
    if isinstance(parameters, list):
        for parameter in parameters[:128]:
            if isinstance(parameter, dict):
                lines.append(
                    "Parameter: {name} kind={kind} offset={offset} size={size}".format(
                        name=_comment_text(parameter.get("name", "unknown")),
                        kind=_comment_text(parameter.get("kind", "Unknown")),
                        offset=parameter.get("offset", "?"),
                        size=parameter.get("storage_size", "?"),
                    )
                )
    if isinstance(parameters, list) and len(parameters) > 128:
        lines.append("Additional parameters omitted from comment: " + str(len(parameters) - 128))
    return "\n".join(lines)[:MAX_COMMENT_CHARS]


def run_import():
    import ida_bytes
    import ida_ida
    import ida_kernwin
    import ida_name
    import ida_nalt
    import ida_segment
    import idc

    artifact_dir = ida_kernwin.ask_dir(False, "Select an NextDumper artifact directory")
    if not artifact_dir:
        return
    reflection_path = os.path.join(artifact_dir, "reflection.json")
    runtime_path = os.path.join(artifact_dir, "runtime.json")
    reflection = _read_json(reflection_path, REFLECTION_SCHEMA_VERSION)
    runtime = _read_json(runtime_path, 5)

    module = runtime.get("module")
    if not isinstance(module, dict):
        raise ValueError("runtime.json has no module identity")
    module_name = os.path.basename(str(module.get("name", "")))
    input_name = os.path.basename(idc.get_input_file_path())
    if module_name and input_name and module_name.casefold() != input_name.casefold():
        if ida_kernwin.ask_yn(
            0,
            "Artifact module is {0}, but the IDA input is {1}.\n"
            "The artifact has no content hash. Continue only if you verified this is the exact same image.".format(
                module_name, input_name
            ),
        ) != 1:
            return
    elif ida_kernwin.ask_yn(
        0,
        "The artifact does not contain a module content hash.\n"
        "Confirm that the IDA input is the exact binary used for this capture.",
    ) != 1:
        return

    architecture = str(module.get("architecture", "")).casefold()
    if architecture not in ("arm32", "arm64"):
        raise ValueError("Artifact has an unsupported module architecture")
    if not ida_ida.inf_get_procname().casefold().startswith("arm"):
        raise ValueError("IDA database processor is not ARM")
    if (architecture == "arm64") != bool(ida_ida.inf_is_64bit()):
        raise ValueError("IDA database bitness does not match the artifact module")

    header, type_count, enum_count, property_count = _build_types_header(artifact_dir, reflection)
    header_path = os.path.join(artifact_dir, "NextDumper_IDA_types.h")
    base_header_path = header_path
    suffix = 1
    while True:
        try:
            with open(header_path, "x", encoding="utf-8", newline="\n") as output:
                output.write(header)
            break
        except FileExistsError:
            header_path = os.path.splitext(base_header_path)[0] + "_" + str(suffix) + ".h"
            suffix += 1
            if suffix > 100:
                raise OSError("Could not choose a non-existing IDA type header path")

    parse_errors = idc.parse_decls(header, 0)
    if parse_errors is None or parse_errors != 0:
        raise ValueError(
            "IDA reported {0} type declaration errors; no address annotations were applied. "
            "The generated header remains at: {1}".format(
                parse_errors, header_path
            )
        )

    try:
        image_base = _as_int(ida_nalt.get_imagebase())
        module_base = _as_int(module.get("base"))
        module_end = _as_int(module.get("end"))
    except (TypeError, ValueError):
        raise ValueError("runtime.json module base/end are invalid")
    if module_end <= module_base:
        raise ValueError("runtime.json module range is invalid")
    module_size = module_end - module_base

    entries = {}
    if _count_shards(reflection, "functions") > MAX_FUNCTIONS:
        raise ValueError("Function count is invalid or exceeds the configured limit")
    for function in _iter_shard_section(artifact_dir, reflection, "functions"):
        if not isinstance(function, dict) or not function.get("header_readable"):
            continue
        for field, label in (("exec_entry_rva", "UFunction execution entry"),
                             ("native_exec_rva", "native function candidate")):
            value = function.get(field)
            if not isinstance(value, str):
                continue
            if field == "native_exec_rva" and not function.get("native_flag"):
                continue
            try:
                rva = _as_int(value)
            except ValueError:
                continue
            if rva <= 0 or rva >= module_size:
                continue
            if image_base < 0 or image_base > 0xFFFFFFFFFFFFFFFF - rva:
                continue
            ea = image_base + rva
            segment = ida_segment.getseg(ea)
            if (
                segment is None
                or ea < segment.start_ea
                or ea >= segment.end_ea
                or not (segment.perm & ida_segment.SEGPERM_EXEC)
            ):
                continue
            if field == "exec_entry_rva":
                observation = function.get("entry_observation", {})
                if not isinstance(observation, dict) or not observation.get("executable") or not observation.get("in_module"):
                    continue
            entries.setdefault(ea, []).append((function, label))

    labels_added = 0
    comments_added = 0
    for ea, references in sorted(entries.items()):
        name = ida_name.get_name(ea)
        if _default_name(name, ea):
            function, label = references[0]
            stem = _identifier(function.get("full_name", function.get("name", "Function")), "Function")
            prefix = "NextDumper_Exec_" if label == "UFunction execution entry" else "NextDumper_Native_"
            if ida_name.set_name(
                ea, prefix + stem + "_RVA_" + format(ea - image_base, "X"),
                ida_name.SN_CHECK | ida_name.SN_NOWARN
            ):
                labels_added += 1
        current_comment = ida_bytes.get_cmt(ea, True) or ""
        if "NextDumper " in current_comment:
            continue
        comments = [current_comment] if current_comment else []
        for function, label in references:
            comments.append(_function_comment(function, label))
        if ida_bytes.set_cmt(ea, "\n\n".join(comments)[:MAX_COMMENT_CHARS], True):
            comments_added += 1

    ida_kernwin.msg(
        "NextDumper IDA import: {0} types, {1} enums, {2} properties; "
        "{3} RVA labels, {4} comments. Type header: {5}\n".format(
            type_count, enum_count, property_count, labels_added, comments_added, header_path
        )
    )


def main():
    try:
        run_import()
    except Exception as error:
        try:
            import ida_kernwin

            ida_kernwin.warning("NextDumper import failed: " + str(error))
        except Exception:
            raise


if __name__ == "__main__":
    main()
